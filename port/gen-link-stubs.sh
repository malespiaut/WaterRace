#!/bin/sh
# Generate port/link-stubs.cpp: a TODO-fatal stub for every function the game references
# but nothing defines (P0 link step). Usage: port/gen-link-stubs.sh BUILD_DIR
# Each stub is a jump to port_todo_fatal() with the symbol name, so no signatures are needed.
ROOT=$(cd "$(dirname "$0")/.." && pwd)
BUILD=${1:?build dir}
TMP=$(mktemp -d)
find "$BUILD/CMakeFiles/WaterRace.dir" -name '*.o' ! -name 'link-stubs.cpp.o' > "$TMP/objs.txt"
xargs nm -u < "$TMP/objs.txt" 2>/dev/null | awk 'NF==2 {print $2}' | sort -u > "$TMP/undef.txt"
xargs nm --defined-only < "$TMP/objs.txt" 2>/dev/null | awk 'NF==3 {print $3}' | sort -u > "$TMP/defined.txt"
nm --defined-only "$ROOT"/../*.a "$BUILD"/Pomme/*.a "$BUILD"/Pomme/*.so 2>/dev/null | awk 'NF==3 {print $3}' | sort -u >> "$TMP/defined.txt"
for lib in /usr/lib/libc.so.6 /usr/lib/libm.so.6 /usr/lib/libstdc++.so.6 /usr/lib/libgcc_s.so.1; do
  [ -e "$lib" ] && nm -D --defined-only "$lib" | awk 'NF==3 {print $3}'
done | sort -u >> "$TMP/defined.txt"
sort -u "$TMP/defined.txt" -o "$TMP/defined.txt"
comm -23 "$TMP/undef.txt" "$TMP/defined.txt" | grep -v '^_GLOBAL_\|^__' > "$TMP/todo.txt"
{
  echo '// P0 link stubs. GENERATED by port/gen-link-stubs.sh: do not edit by hand.'
  echo '// Each symbol jumps to port_todo_fatal, which aborts with the symbol name.'
  echo '#include <cstdio>'
  echo '#include <cstdlib>'
  echo 'extern "C" [[noreturn]] void port_todo_fatal_c(const char* name) {'
  echo '  std::fprintf(stderr, "WaterRace port: unimplemented %s\n", name);'
  echo '  std::abort();'
  echo '}'
  i=0
  while read -r sym; do
    i=$((i+1))
    printf 'asm(".section .rodata\\n.Lportstub%d: .string \\"%s\\"\\n.text\\n.globl %s\\n.type %s,@function\\n%s: leaq .Lportstub%d(%%rip), %%rdi\\n jmp port_todo_fatal_c\\n");\n' "$i" "$sym" "$sym" "$sym" "$sym" "$i"
  done < "$TMP/todo.txt"
} > "$ROOT/port/link-stubs.cpp"
echo "stubs: $(wc -l < "$TMP/todo.txt")"
rm -rf "$TMP"
